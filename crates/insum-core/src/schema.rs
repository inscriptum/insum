//! Schema artifact — the machine-readable snapshot of the editor's
//! ProseMirror schema (spec §4.7). One source of truth: the plugin
//! generates `schema.json` in its own directory at startup. The CLI never
//! hand-maintains a schema copy; the bundled fallback is a snapshot of the
//! plugin artifact, refreshed when the plugin schema changes.
//!
//! The artifact hash is SHA-256 over the RFC 8785 canonical JSON of the
//! artifact without `schema_hash` and `plugin_version`; the scope is
//! declared by `schema_hash_scope` in the artifact itself.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::Value;
use sha2::{Digest, Sha256};

use crate::canon::canonical_json;
use crate::error::{ErrorCode, UmError};
use crate::limits::Limits;

/// Vault-relative location of the plugin's runtime artifact.
const PLUGIN_SCHEMA_SUBPATH: &str = ".obsidian/plugins/inscriptum/schema.json";

/// Bundled fallback: a snapshot of the plugin's runtime artifact kept in
/// `schema/inscriptum-schema.json` (generated by the plugin, never edited
/// by hand; `plugin_version` is excluded from the hash, so refreshes are
/// rare). Reserve for reading and diagnostics only — it is not evidence of
/// applicability to a concrete document.
const BUNDLED_ARTIFACT: &str = include_str!("../../../schema/inscriptum-schema.json");

/// The parsed schema artifact: typed views over the raw JSON, unknown
/// fields stay in `raw`.
#[derive(Debug, Clone)]
pub struct SchemaArtifact {
    pub raw: Value,
    pub schema_id: String,
    pub schema_version: u32,
    /// Declared fingerprint, `sha256:<64 hex>`.
    pub schema_hash: String,
    pub plugin_version: Option<String>,
    pub top_node: Option<String>,
    pub validation_capability: String,
    pub validation_limits: Vec<String>,
    pub nodes: BTreeMap<String, NodeSpec>,
    pub marks: BTreeMap<String, MarkSpec>,
}

/// One node type of the artifact. `marks` is the PM `allowsMarkType`
/// resolution at generation time; the CLI does not enforce it (partial
/// capability — the differential corpus owns that proof).
#[derive(Debug, Clone)]
pub struct NodeSpec {
    pub content: Option<String>,
    pub groups: Vec<String>,
    pub top_node: bool,
    /// Declared attribute specs (`{ "default": ... }` objects), raw.
    pub attrs: BTreeMap<String, Value>,
    pub marks: Vec<String>,
    pub addressable: bool,
    pub inline_content: bool,
    pub searchable: bool,
    pub example: Option<Value>,
}

/// One mark type of the artifact.
#[derive(Debug, Clone)]
pub struct MarkSpec {
    pub group: Option<String>,
    pub attrs: BTreeMap<String, Value>,
}

impl SchemaArtifact {
    /// Parse the artifact from JSON. Required: `schema_id`, `schema_version`,
    /// `schema_hash`, `nodes`, `validation_capability`; everything else is
    /// optional and defaults.
    pub fn parse(raw: Value) -> Result<Self, UmError> {
        let invalid = |message: String| {
            UmError::new(ErrorCode::SchemaArtifactInvalid, message).with_hint(
                "The artifact is generated by the plugin in its own directory; regenerate it by reloading the plugin.",
            )
        };
        let object = raw
            .as_object()
            .ok_or_else(|| invalid("schema artifact is not a JSON object".into()))?;

        let schema_id = object
            .get("schema_id")
            .and_then(Value::as_str)
            .ok_or_else(|| invalid("schema artifact is missing string `schema_id`".into()))?
            .to_owned();
        let schema_version = object
            .get("schema_version")
            .and_then(Value::as_u64)
            .ok_or_else(|| invalid("schema artifact is missing integer `schema_version`".into()))?
            .try_into()
            .map_err(|_| invalid("`schema_version` does not fit u32".into()))?;
        let schema_hash = object
            .get("schema_hash")
            .and_then(Value::as_str)
            .ok_or_else(|| invalid("schema artifact is missing string `schema_hash`".into()))?
            .to_owned();
        let validation_capability = object
            .get("validation_capability")
            .and_then(Value::as_str)
            .ok_or_else(|| {
                invalid("schema artifact is missing string `validation_capability`".into())
            })?
            .to_owned();
        let nodes_value = object
            .get("nodes")
            .and_then(Value::as_object)
            .ok_or_else(|| invalid("schema artifact is missing object `nodes`".into()))?;

        let mut nodes = BTreeMap::new();
        for (name, spec) in nodes_value {
            nodes.insert(name.clone(), parse_node_spec(spec).map_err(invalid)?);
        }
        let mut marks = BTreeMap::new();
        if let Some(marks_value) = object.get("marks").and_then(Value::as_object) {
            for (name, spec) in marks_value {
                marks.insert(name.clone(), parse_mark_spec(spec).map_err(invalid)?);
            }
        }

        Ok(Self {
            plugin_version: object
                .get("plugin_version")
                .and_then(Value::as_str)
                .map(str::to_owned),
            top_node: object
                .get("top_node")
                .and_then(Value::as_str)
                .map(str::to_owned),
            validation_limits: object
                .get("validation_limits")
                .and_then(Value::as_array)
                .map(|limits| {
                    limits
                        .iter()
                        .filter_map(Value::as_str)
                        .map(str::to_owned)
                        .collect()
                })
                .unwrap_or_default(),
            raw,
            schema_id,
            schema_version,
            schema_hash,
            validation_capability,
            nodes,
            marks,
        })
    }

    /// Recompute the fingerprint over the canonical artifact without
    /// `schema_hash` and `plugin_version` and compare it with the declared
    /// one.
    pub fn verify_hash(&self) -> bool {
        self.schema_hash == compute_hash(&self.raw)
    }
}

/// SHA-256 of the RFC 8785 canonical JSON of the artifact without the
/// `schema_hash` and `plugin_version` fields.
pub fn compute_hash(raw: &Value) -> String {
    let mut object = raw.as_object().cloned().unwrap_or_default();
    object.remove("schema_hash");
    object.remove("plugin_version");
    let canonical = canonical_json(&Value::Object(object));
    let digest = Sha256::digest(canonical.as_bytes());
    format!("sha256:{:x}", digest)
}

fn parse_node_spec(spec: &Value) -> Result<NodeSpec, String> {
    let object = spec
        .as_object()
        .ok_or_else(|| "node spec is not a JSON object".to_owned())?;
    let mut attrs = BTreeMap::new();
    if let Some(attrs_value) = object.get("attrs").and_then(Value::as_object) {
        for (name, value) in attrs_value {
            attrs.insert(name.clone(), value.clone());
        }
    }
    Ok(NodeSpec {
        content: object
            .get("content")
            .and_then(Value::as_str)
            .map(str::to_owned),
        groups: object
            .get("groups")
            .and_then(Value::as_array)
            .map(|groups| {
                groups
                    .iter()
                    .filter_map(Value::as_str)
                    .map(str::to_owned)
                    .collect()
            })
            .unwrap_or_default(),
        top_node: object
            .get("top_node")
            .and_then(Value::as_bool)
            .unwrap_or(false),
        attrs,
        marks: object
            .get("marks")
            .and_then(Value::as_array)
            .map(|marks| {
                marks
                    .iter()
                    .filter_map(Value::as_str)
                    .map(str::to_owned)
                    .collect()
            })
            .unwrap_or_default(),
        addressable: object
            .get("addressable")
            .and_then(Value::as_bool)
            .unwrap_or(false),
        inline_content: object
            .get("inline_content")
            .and_then(Value::as_bool)
            .unwrap_or(false),
        searchable: object
            .get("searchable")
            .and_then(Value::as_bool)
            .unwrap_or(false),
        example: object.get("example").cloned(),
    })
}

fn parse_mark_spec(spec: &Value) -> Result<MarkSpec, String> {
    let object = spec
        .as_object()
        .ok_or_else(|| "mark spec is not a JSON object".to_owned())?;
    let mut attrs = BTreeMap::new();
    if let Some(attrs_value) = object.get("attrs").and_then(Value::as_object) {
        for (name, value) in attrs_value {
            attrs.insert(name.clone(), value.clone());
        }
    }
    Ok(MarkSpec {
        group: object
            .get("group")
            .and_then(Value::as_str)
            .map(str::to_owned),
        attrs,
    })
}

/// Where the applicable artifact came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SchemaSource {
    /// The user pointed `--schema` at a file.
    Explicit,
    /// Found by the vault rule: `.obsidian/plugins/inscriptum/schema.json`
    /// above the target file or working directory.
    PluginRuntime,
    /// The CLI's bundled snapshot; reserve for reading and diagnostics.
    BundledFallback,
}

impl SchemaSource {
    pub fn as_str(self) -> &'static str {
        match self {
            SchemaSource::Explicit => "explicit",
            SchemaSource::PluginRuntime => "plugin-runtime",
            SchemaSource::BundledFallback => "bundled-fallback",
        }
    }
}

/// A loaded artifact together with its provenance.
#[derive(Debug, Clone)]
pub struct ResolvedSchema {
    pub source: SchemaSource,
    pub source_path: Option<PathBuf>,
    /// Cheap to share: artifacts are read once and handed to every file or
    /// consumer without deep clones.
    pub artifact: std::sync::Arc<SchemaArtifact>,
    pub hash_verified: bool,
}

/// Resolve the applicable artifact: explicit `--schema` path first, then the
/// plugin runtime artifact found by walking up from `start`, then the bundled
/// fallback. An explicit file that is missing, unreadable or corrupt is an
/// error (the user pointed at it); a corrupt vault-found artifact is reported
/// by the caller through the error.
pub fn resolve(
    explicit: Option<&Path>,
    start: &Path,
    limits: &Limits,
) -> Result<ResolvedSchema, UmError> {
    if let Some(path) = explicit {
        if !path.is_file() {
            return Err(UmError::new(
                ErrorCode::SchemaUnavailable,
                format!("schema artifact not found: {}", path.display()),
            )
            .with_hint("Point --schema at a schema.json generated by the plugin, or omit it."));
        }
        let artifact = load_artifact_file(path, limits)?;
        let hash_verified = artifact.verify_hash();
        return Ok(ResolvedSchema {
            source: SchemaSource::Explicit,
            source_path: Some(path.to_path_buf()),
            artifact: std::sync::Arc::new(artifact),
            hash_verified,
        });
    }

    if let Some(path) = find_plugin_artifact(start) {
        let artifact = load_artifact_file(&path, limits)?;
        let hash_verified = artifact.verify_hash();
        return Ok(ResolvedSchema {
            source: SchemaSource::PluginRuntime,
            source_path: Some(path),
            artifact: std::sync::Arc::new(artifact),
            hash_verified,
        });
    }

    let raw: Value = serde_json::from_str(BUNDLED_ARTIFACT)
        .map_err(|err| UmError::internal(format!("bundled artifact is corrupt: {err}")))?;
    let artifact = SchemaArtifact::parse(raw)?;
    let hash_verified = artifact.verify_hash();
    Ok(ResolvedSchema {
        source: SchemaSource::BundledFallback,
        source_path: None,
        artifact: std::sync::Arc::new(artifact),
        hash_verified,
    })
}

/// Walk up from `start` (a file or directory) looking for the plugin's
/// runtime artifact. A bare file name has an empty parent — that means the
/// working directory, not "no vault".
pub fn find_plugin_artifact(start: &Path) -> Option<PathBuf> {
    let start_dir = if start.is_dir() {
        start
    } else {
        match start.parent() {
            Some(parent) if !parent.as_os_str().is_empty() => parent,
            _ => Path::new("."),
        }
    };
    for dir in start_dir.ancestors() {
        let candidate = dir.join(PLUGIN_SCHEMA_SUBPATH);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    None
}

fn load_artifact_file(path: &Path, limits: &Limits) -> Result<SchemaArtifact, UmError> {
    let bytes = std::fs::read(path)?;
    if bytes.len() > limits.max_schema_bytes {
        return Err(UmError::new(
            ErrorCode::LimitExceeded,
            format!(
                "schema artifact larger than UM_MAX_SCHEMA_BYTES ({})",
                limits.max_schema_bytes
            ),
        ));
    }
    let raw: Value = serde_json::from_slice(&bytes).map_err(|err| {
        UmError::new(
            ErrorCode::SchemaArtifactInvalid,
            format!(
                "schema artifact at {} is not valid JSON: {err}",
                path.display()
            ),
        )
    })?;
    SchemaArtifact::parse(raw).map_err(|mut err| {
        err.message = format!("{} (at {})", err.message, path.display());
        err
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    use std::path::PathBuf;

    /// A minimal but structurally honest artifact fixture with a correct
    /// self-hash.
    fn fixture_artifact() -> Value {
        let mut raw = json!({
            "schema_id": "inscriptum",
            "schema_version": 1,
            "schema_hash": "",
            "top_node": "noteDoc",
            "validation_capability": "partial",
            "nodes": {
                "noteDoc": {
                    "content": "noteTitle block*",
                    "groups": [],
                    "attrs": {},
                    "marks": [],
                    "addressable": false,
                    "inline_content": false,
                    "searchable": false
                },
                "paragraph": {
                    "content": "inline*",
                    "groups": ["block"],
                    "attrs": {"id": {"default": null}},
                    "marks": ["bold"],
                    "addressable": true,
                    "inline_content": true,
                    "searchable": true,
                    "example": {"type": "paragraph", "attrs": {"id": null}, "content": []}
                }
            },
            "marks": {
                "bold": {"group": null, "attrs": {}}
            }
        });
        raw["schema_hash"] = json!(compute_hash(&raw));
        raw
    }

    fn write_fixture(dir: &Path, name: &str) -> PathBuf {
        let path = dir.join(name);
        std::fs::write(&path, serde_json::to_vec(&fixture_artifact()).unwrap()).unwrap();
        path
    }

    #[test]
    fn parse_extracts_typed_fields() {
        let artifact = SchemaArtifact::parse(fixture_artifact()).unwrap();
        assert_eq!(artifact.schema_id, "inscriptum");
        assert_eq!(artifact.schema_version, 1);
        assert_eq!(artifact.top_node.as_deref(), Some("noteDoc"));
        assert_eq!(artifact.validation_capability, "partial");
        assert!(artifact.nodes.contains_key("paragraph"));
        assert!(artifact.nodes["paragraph"].addressable);
        assert!(artifact.marks.contains_key("bold"));
    }

    #[test]
    fn parse_rejects_missing_required_fields() {
        let raw = json!({"schema_id": "inscriptum"});
        let err = SchemaArtifact::parse(raw).unwrap_err();
        assert_eq!(err.code, ErrorCode::SchemaArtifactInvalid);
        assert_eq!(err.code.exit_code(), 6);
    }

    #[test]
    fn hash_verifies_for_consistent_artifact_and_fails_when_tampered() {
        let raw = fixture_artifact();
        let artifact = SchemaArtifact::parse(raw.clone()).unwrap();
        assert!(artifact.verify_hash());

        let mut tampered = raw.clone();
        tampered["validation_capability"] = json!("full");
        let tampered = SchemaArtifact::parse(tampered).unwrap();
        assert!(!tampered.verify_hash());
    }

    #[test]
    fn hash_ignores_schema_hash_and_plugin_version_fields() {
        let mut raw = fixture_artifact();
        raw["plugin_version"] = json!("0.0.0");
        let artifact = SchemaArtifact::parse(raw).unwrap();
        assert!(
            artifact.verify_hash(),
            "plugin_version must not shift the hash"
        );
    }

    #[test]
    fn explicit_resolution_loads_and_verifies() {
        let dir = tempfile::tempdir().unwrap();
        let path = write_fixture(dir.path(), "schema.json");
        let resolved = resolve(Some(&path), dir.path(), &Limits::defaults()).unwrap();
        assert_eq!(resolved.source, SchemaSource::Explicit);
        assert!(resolved.hash_verified);
        assert_eq!(resolved.source_path.as_deref(), Some(path.as_path()));
    }

    #[test]
    fn explicit_missing_file_is_schema_unavailable() {
        let dir = tempfile::tempdir().unwrap();
        let err = resolve(
            Some(&dir.path().join("nope.json")),
            dir.path(),
            &Limits::defaults(),
        )
        .unwrap_err();
        assert_eq!(err.code, ErrorCode::SchemaUnavailable);
        assert_eq!(err.code.exit_code(), 6);
    }

    #[test]
    fn plugin_runtime_artifact_found_by_walking_up() {
        let dir = tempfile::tempdir().unwrap();
        let plugin_dir = dir.path().join(".obsidian/plugins/inscriptum");
        std::fs::create_dir_all(&plugin_dir).unwrap();
        write_fixture(&plugin_dir, "schema.json");
        let nested = dir.path().join("a/b");
        std::fs::create_dir_all(&nested).unwrap();

        let found = find_plugin_artifact(&nested).unwrap();
        assert_eq!(
            found,
            plugin_dir.join("schema.json"),
            "the walk starts at the target and goes up"
        );

        let resolved = resolve(None, &nested, &Limits::defaults()).unwrap();
        assert_eq!(resolved.source, SchemaSource::PluginRuntime);
        assert!(resolved.hash_verified);
    }

    #[test]
    fn no_vault_falls_back_to_bundled() {
        let dir = tempfile::tempdir().unwrap();
        let resolved = resolve(None, dir.path(), &Limits::defaults()).unwrap();
        assert_eq!(resolved.source, SchemaSource::BundledFallback);
        assert!(resolved.source_path.is_none());
        assert!(
            resolved.hash_verified,
            "the bundled snapshot is self-consistent"
        );
    }

    #[test]
    fn bundled_artifact_is_parseable_and_hash_correct() {
        let raw: Value = serde_json::from_str(BUNDLED_ARTIFACT).unwrap();
        let artifact = SchemaArtifact::parse(raw).unwrap();
        assert!(
            artifact.verify_hash(),
            "the shipped snapshot must keep its declared hash"
        );
    }
}
