//! `insum validate` — read-only structural validation (spec §6.6).
//!
//! Stage A checks containers, manifests, note JSON structure, entry names,
//! limits and (when a document is marked `features.block_ids`) ID grammar
//! and uniqueness. The level is always `structural`: without a schema
//! artifact the CLI must not claim schema/full validation (§6.6, §15.5 №48).

use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use insum_core::{ErrorCode, Limits, UmError};

use crate::support::{Revs, collect_files, read_notes, render_path};

pub fn run(
    paths: &[PathBuf],
    strict: bool,
    schema: Option<&Path>,
    hidden: bool,
    limits: &Limits,
) -> Result<Value, UmError> {
    if paths.is_empty() {
        return Err(UmError::usage("validate requires at least one path"));
    }
    if let Some(schema_path) = schema {
        if !schema_path.exists() {
            return Err(UmError::new(
                ErrorCode::SchemaUnavailable,
                format!("schema artifact not found: {}", schema_path.display()),
            )
            .with_hint("Point --schema at a schema.json generated by the plugin, or omit it."));
        }
        // A stage A CLI cannot perform schema-level validation yet: claiming
        // it would violate §6.6/§15.5 №48.
        return Err(UmError::new(
            ErrorCode::SchemaValidationIncomplete,
            "schema-level validation is not available on stage A",
        )
        .with_hint(
            "Structural validation runs without --schema; schema/full levels arrive with the schema-cli task.",
        ));
    }

    let (files, walk_errors) = collect_files(paths, hidden)?;
    let mut file_results = Vec::new();
    let mut all_valid = true;

    // locations that could not be enumerated lower the result (spec §11)
    for walk_error in &walk_errors {
        all_valid = false;
        file_results.push(json!({
            "path": walk_error.path,
            "valid": false,
            "notes": [],
            "errors": [{"code": "IO_ERROR", "message": walk_error.message}],
            "warnings": [],
        }));
    }

    for file in &files {
        let rendered = render_path(file);
        let result = validate_file(file, strict, limits);
        match result {
            Ok(mut file_json) => {
                file_json["path"] = json!(rendered);
                if file_json["valid"] != json!(true) {
                    all_valid = false;
                }
                file_results.push(file_json);
            }
            Err(err) => {
                all_valid = false;
                file_results.push(json!({
                    "path": rendered,
                    "valid": false,
                    "notes": [],
                    "errors": [{
                        "code": err.code.as_str(),
                        "message": err.message,
                    }],
                    "warnings": [],
                }));
            }
        }
    }

    Ok(json!({
        "api_version": 1,
        "validation_level": "structural",
        "valid": all_valid,
        "files": file_results,
    }))
}

fn validate_file(path: &Path, strict: bool, limits: &Limits) -> Result<Value, UmError> {
    let views = read_notes(path, None, limits, Revs::Skip)?.views;
    let mut notes = Vec::new();
    let mut file_valid = true;

    for view in views {
        // validation logic lives in insum-core (§14); the CLI
        // only shapes the output
        let validation = insum_core::validate_note_doc(&view.doc, view.block_ids_enabled, limits)?;
        if !validation.valid() {
            file_valid = false;
        }
        if strict && !validation.warnings.is_empty() {
            // §6.6/§10.2: --strict promotes warnings to errors. NOTE_DOC_INVALID
            // is the data-level code the §11 registry offers for it (exit 4);
            // without --strict a warning never flips `valid`.
            file_valid = false;
            let mut strict_errors = warnings_as_errors(&validation.warnings);
            strict_errors.extend(diagnostics(&validation.errors));
            notes.push(json!({
                "id": view.note_id,
                "valid": false,
                "errors": strict_errors,
                "warnings": [],
            }));
            continue;
        }
        notes.push(json!({
            "id": view.note_id,
            "valid": validation.valid(),
            "errors": diagnostics(&validation.errors),
            "warnings": diagnostics(&validation.warnings),
        }));
    }

    Ok(json!({
        "valid": file_valid,
        "notes": notes,
        "errors": [],
        "warnings": [],
    }))
}

fn warnings_as_errors(warnings: &[insum_core::Diag]) -> Vec<Value> {
    warnings
        .iter()
        .map(|warning| {
            json!({
                "code": "NOTE_DOC_INVALID",
                "message": format!("strict: {} ({})", warning.message, warning.code)
            })
        })
        .collect()
}

fn diagnostics(diags: &[insum_core::Diag]) -> Vec<Value> {
    diags
        .iter()
        .map(|diag| json!({"code": diag.code, "message": diag.message}))
        .collect()
}
